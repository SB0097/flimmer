import { File } from 'expo-file-system';

import type { CaptionTrack } from '@/services/video-source/types';
import { captionUrl, loadCaption, validateVtt } from '../captions';
import { toCaptionTracks } from '@/services/video-source/youtubejs/captions';

const mockWrite = jest.fn();
jest.mock('expo-file-system', () => ({
  Paths: { cache: 'file:///cache' },
  File: jest
    .fn()
    .mockImplementation(() => ({ uri: 'file:///cache/captions.vtt', write: mockWrite })),
}));

const track: CaptionTrack = {
  videoId: 'M7lc1UVf-VE',
  id: '.en',
  language: 'en',
  name: 'Englisch',
  autoGenerated: false,
  url: 'https://www.youtube.com/api/timedtext?v=M7lc1UVf-VE&signature=abc%2Bdef&fmt=json3',
  headers: { 'User-Agent': 'visionos' },
};
const vtt =
  'WEBVTT\nKind: captions\nLanguage: en\n\n00:00:10.349 --> 00:00:11.349\nHello <c>world</c>\n';
const originalFetch = global.fetch;
beforeEach(() => jest.clearAllMocks());
afterEach(() => {
  global.fetch = originalFetch;
});

it('behält Signatur und Video-ID bei und fordert WebVTT an', () => {
  const url = new URL(captionUrl(track));
  expect(url.searchParams.get('signature')).toBe('abc+def');
  expect(url.searchParams.get('fmt')).toBe('vtt');
  expect(url.searchParams.get('v')).toBe(track.videoId);
  for (const url of ['file:///x', 'https://youtube.com.evil.test/x', 'http://youtube.com/x'])
    expect(() => captionUrl({ ...track, url })).toThrow('Adresse');
});

it('unterscheidet manuelle und automatisch erzeugte Spuren derselben Sprache', () => {
  const tracks = toCaptionTracks(
    'video',
    [
      {
        base_url: track.url,
        name: { toString: () => 'English' },
        vss_id: '.en',
        language_code: 'en',
      },
      {
        base_url: track.url,
        name: { toString: () => 'English (auto)' },
        vss_id: 'a.en',
        language_code: 'en',
        kind: 'asr',
      },
    ],
    track.headers,
  );
  expect(tracks.map((t) => [t.id, t.autoGenerated])).toEqual([
    ['.en', false],
    ['a.en', true],
  ]);
  expect(tracks[1]).toMatchObject({ videoId: 'video', headers: track.headers });
  expect(toCaptionTracks('video', undefined)).toEqual([]);
});

it('normalisiert Zeilenenden und akzeptiert auch ASR-WebVTT mit Zeit-/CSS-Tags', () => {
  expect(validateVtt('\uFEFF' + vtt.replace(/\n/g, '\r\n'))).toBe(vtt);
  expect(
    validateVtt(vtt.replace('Hello <c>world</c>', 'hey<00:00:10.400><c> everybody</c>')),
  ).toContain('<c>');
  for (const input of [
    '',
    '<html>Error</html>',
    'WEBVTT\n\n',
    'WEBVTT\n' + 'x'.repeat(5 * 1024 * 1024),
  ])
    expect(() => validateVtt(input)).toThrow('lesbaren');
});

it('schreibt nur gültige, vollständig geladene Untertitel in den Cache', async () => {
  global.fetch = jest
    .fn()
    .mockResolvedValue({ ok: true, headers: new Headers(), text: async () => vtt });
  const signal = new AbortController().signal;
  expect(await loadCaption(track, signal)).toBe('file:///cache/captions.vtt');
  expect(fetch).toHaveBeenCalledWith(expect.stringContaining('fmt=vtt'), {
    signal,
    headers: track.headers,
  });
  expect(mockWrite).toHaveBeenCalledWith(vtt);
});

it('schreibt bei HTTP-Fehler, Übergröße oder abgebrochener Auswahl keine Datei', async () => {
  for (const response of [
    { ok: false, status: 403 },
    { ok: true, headers: new Headers({ 'content-length': '99999999' }) },
    { ok: true, headers: new Headers(), text: async () => '<html>error</html>' },
  ]) {
    global.fetch = jest.fn().mockResolvedValue(response);
    await expect(loadCaption(track, new AbortController().signal)).rejects.toThrow();
  }
  global.fetch = jest
    .fn()
    .mockResolvedValue({ ok: true, headers: new Headers(), text: async () => vtt });
  const aborted = new AbortController();
  aborted.abort();
  await expect(loadCaption(track, aborted.signal)).rejects.toThrow('abgebrochen');
  expect(File).not.toHaveBeenCalled();
  expect(mockWrite).not.toHaveBeenCalled();
});

it('zeigt bei einem Verbindungsabbruch eine verständliche Meldung statt nativer Diagnosedaten', async () => {
  global.fetch = jest
    .fn()
    .mockRejectedValue(new TypeError('fetch failed: java.net.UnknownHostException'));
  await expect(loadCaption(track, new AbortController().signal)).rejects.toThrow(
    'Untertitel konnten nicht geladen werden. Prüfe die Verbindung und versuche es erneut.',
  );
  expect(mockWrite).not.toHaveBeenCalled();
});
