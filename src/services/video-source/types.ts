/**
 * Austauschbare Datenquelle für Videos.
 *
 * Die App greift nur über dieses Interface auf YouTube zu. Ändert YouTube etwas,
 * muss nur die jeweilige Implementierung angepasst werden. Standard ist
 * YouTube.js; der NewPipeExtractor kann später als natives Modul folgen.
 */

export interface Thumbnail {
  url: string;
  width: number;
  height: number;
}

export interface ChannelRef {
  id: string;
  name: string;
  avatar?: Thumbnail;
  /** z. B. „15,8 Mio. Abonnenten“ */
  subscriberCountText?: string;
}

export interface VideoSummary {
  id: string;
  title: string;
  channel: ChannelRef;
  /** Länge in Sekunden, `undefined` bei Livestreams */
  durationSeconds?: number;
  viewCountText?: string;
  publishedText?: string;
  thumbnails: Thumbnail[];
  isLive: boolean;
}

export interface VideoDetails extends VideoSummary {
  description: string;
  viewCount?: number;
  likeCount?: number;
  /** Absolutes Datum, z. B. „Premiere am 31.12.2021“ */
  dateText?: string;
}

/** Alles für die Player-Seite außer dem Stream selbst */
export interface WatchPage {
  captions?: CaptionTrack[];
  details: VideoDetails;
  related: VideoSummary[];
  /** Weitere „Nächste Videos“ nachladen */
  moreRelated?: () => Promise<RelatedPage>;
}

export interface RelatedPage {
  items: VideoSummary[];
  more?: () => Promise<RelatedPage>;
}

/** Abspielbare Quelle, direkt für expo-video verwendbar */
export interface PlaybackSource {
  /** Android: vorbereitete WebVTT-Dateien, vom nativen Player gerendert. */
  externalSubtitles?: { uri: string; language: string; label: string }[];
  uri: string;
  contentType: 'hls' | 'dash' | 'progressive';
  headers?: Record<string, string>;
  /** Über welchen Weg die Quelle ermittelt wurde (für die Diagnose) */
  via: string;
}

/** Ein einzelner Versuch beim Ermitteln der Streams (für die Diagnose) */
export interface StreamAttempt {
  via: string;
  ok: boolean;
  message: string;
}

export interface StreamResult {
  captions?: CaptionTrack[];
  source: PlaybackSource;
  details?: VideoDetails;
  attempts: StreamAttempt[];
}

export interface CaptionTrack {
  videoId: string;
  id: string;
  language: string;
  name: string;
  autoGenerated: boolean;
  url: string;
  headers?: Record<string, string>;
}

export class StreamUnavailableError extends Error {
  constructor(
    message: string,
    readonly attempts: StreamAttempt[],
  ) {
    super(message);
    this.name = 'StreamUnavailableError';
  }
}

export interface Comment {
  id: string;
  author: { id?: string; name: string; avatar?: Thumbnail; isUploader: boolean };
  text: string;
  publishedText?: string;
  likeCount?: number;
  replyCount: number;
  isPinned: boolean;
  /** Vom Kanal mit Herz markiert */
  isHearted: boolean;
  loadReplies?: () => Promise<CommentsPage>;
}

export interface CommentsPage {
  items: Comment[];
  more?: () => Promise<CommentsPage>;
}

export interface CommentsResult extends CommentsPage {
  /** z. B. „10.625“ */
  countText?: string;
}

export type CommentSort = 'top' | 'newest';

export interface SearchPage {
  items: VideoSummary[];
  /** Weiterblättern; `undefined`, wenn es keine weiteren Ergebnisse gibt */
  next?: () => Promise<SearchPage>;
}

export interface ChannelPage extends SearchPage {
  channel: ChannelRef;
  description: string;
}

export interface VideoSource {
  readonly name: string;
  search(query: string): Promise<SearchPage>;
  getHome(): Promise<SearchPage>;
  getChannel(id: string): Promise<ChannelPage>;
  getStreams(id: string): Promise<StreamResult>;
  getWatchPage(id: string): Promise<WatchPage>;
  getComments(id: string, sort: CommentSort): Promise<CommentsResult>;
}
