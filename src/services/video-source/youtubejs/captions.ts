import type { CaptionTrack } from '../types';

interface TrackData {
  base_url: string;
  name: { toString(): string };
  vss_id: string;
  language_code: string;
  kind?: string;
}

export function toCaptionTracks(
  videoId: string,
  tracks: TrackData[] | undefined,
  headers?: Record<string, string>,
): CaptionTrack[] {
  return (tracks ?? [])
    .filter((t) => t.base_url && t.language_code)
    .map((t) => ({
      videoId,
      id: t.vss_id || `${t.language_code}:${t.kind ?? 'manual'}`,
      language: t.language_code,
      name: t.name.toString() || t.language_code,
      autoGenerated: t.kind === 'asr',
      url: t.base_url,
      headers,
    }));
}
